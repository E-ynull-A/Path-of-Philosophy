/*
 * Real photos and artworks from Wikimedia Commons, stored in the project
 * (public/photos/), so the site works on any host and offline — no hotlinking.
 *
 * Every file was checked through the Wikimedia API and its licence allows
 * reuse (public domain, CC0, CC BY or CC BY-SA). CC BY / BY-SA require
 * crediting the author — the app does this on the Sources page (linked from
 * the footer on every page), using `page`, `artist` and `license`. Keep it.
 *
 * Paths are relative ("photos/…"), which works with the hash router and the
 * relative `base` in vite.config.ts. If a photo cannot load, <Art> and
 * <Medallion> fall back to the hand-drawn SVG / initials automatically.
 */

